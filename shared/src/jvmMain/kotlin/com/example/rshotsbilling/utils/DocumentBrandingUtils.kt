package com.example.rshotsbilling.utils

import com.itextpdf.text.*
import com.itextpdf.text.pdf.*
import java.text.SimpleDateFormat
import java.util.*

object DocumentBrandingUtils {

    fun addHeader(document: Document, title: String, logoBytes: ByteArray?) {
        val titleFont = Font(Font.FontFamily.HELVETICA, 16f, Font.BOLD)
        val companyFont = Font(Font.FontFamily.HELVETICA, 12f, Font.BOLD)
        val normalFont = Font(Font.FontFamily.HELVETICA, 8f, Font.NORMAL)
        val boldFont = Font(Font.FontFamily.HELVETICA, 8f, Font.BOLD)

        // Logo and Title Row
        val headerTable = PdfPTable(2)
        headerTable.widthPercentage = 100f
        headerTable.setWidths(floatArrayOf(30f, 70f))
        headerTable.spacingAfter = 10f

        // Logo
        if (logoBytes != null) {
            try {
                val image = Image.getInstance(logoBytes)
                image.scaleToFit(100f, 100f)
                val cell = PdfPCell(image)
                cell.border = Rectangle.NO_BORDER
                headerTable.addCell(cell)
            } catch (e: Exception) {
                headerTable.addCell(createEmptyCell())
            }
        } else {
            headerTable.addCell(createEmptyCell())
        }

        // Company Details
        val detailsCell = PdfPCell()
        detailsCell.border = Rectangle.NO_BORDER
        detailsCell.horizontalAlignment = Element.ALIGN_RIGHT
        
        detailsCell.addElement(Paragraph(title.uppercase(), titleFont).apply { alignment = Element.ALIGN_RIGHT })
        detailsCell.addElement(Paragraph(BusinessConfig.COMPANY_NAME, companyFont).apply { alignment = Element.ALIGN_RIGHT })
        detailsCell.addElement(Paragraph(UserSession.companyAddress, normalFont).apply { alignment = Element.ALIGN_RIGHT })
        detailsCell.addElement(Paragraph("Phone: ${UserSession.companyPhone} | Email: ${UserSession.companyEmail}", normalFont).apply { alignment = Element.ALIGN_RIGHT })
        if (UserSession.companyWebsite.isNotEmpty()) {
            detailsCell.addElement(Paragraph("Website: ${UserSession.companyWebsite}", normalFont).apply { alignment = Element.ALIGN_RIGHT })
        }
        detailsCell.addElement(Paragraph("KRA PIN: ${BusinessConfig.BUSINESS_KRA_PIN}", boldFont).apply { alignment = Element.ALIGN_RIGHT })
        
        headerTable.addCell(detailsCell)
        document.add(headerTable)
        
        val line = Paragraph()
        line.add(Chunk(com.itextpdf.text.pdf.draw.LineSeparator(1f, 100f, BaseColor.BLACK, Element.ALIGN_CENTER, -2f)))
        document.add(line)
        document.add(Paragraph(" "))
    }

    fun addFooter(writer: PdfWriter, document: Document, status: String = "APPROVED") {
        val normalFont = Font(Font.FontFamily.HELVETICA, 7f, Font.NORMAL)
        val boldFont = Font(Font.FontFamily.HELVETICA, 7f, Font.BOLD)
        
        val timestamp = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault()).format(Date())
        val generatedBy = UserSession.displayName ?: "System"
        
        val footerTable = PdfPTable(3)
        footerTable.totalWidth = document.right() - document.left()
        footerTable.widthPercentage = 100f
        
        val cell1 = PdfPCell(Phrase("Generated by RShotsBilling", normalFont))
        cell1.border = Rectangle.TOP
        footerTable.addCell(cell1)
        
        val cell2 = PdfPCell(Phrase("Status: $status", boldFont))
        cell2.horizontalAlignment = Element.ALIGN_CENTER
        cell2.border = Rectangle.TOP
        footerTable.addCell(cell2)
        
        val cell3 = PdfPCell(Phrase("Generated: $timestamp\nBy: $generatedBy", normalFont))
        cell3.horizontalAlignment = Element.ALIGN_RIGHT
        cell3.border = Rectangle.TOP
        footerTable.addCell(cell3)
        
        footerTable.writeSelectedRows(0, -1, document.left(), document.bottom() - 10f, writer.directContent)
        
        // Add stamp
        StampUtility.drawStamp(writer.directContent, document.right() - 150f, document.bottom() + 40f)
    }

    private fun createEmptyCell(): PdfPCell {
        val cell = PdfPCell()
        cell.border = Rectangle.NO_BORDER
        return cell
    }
}
