package com.example.rshotsbilling.utils

object ExcelExporter {

    fun exportCSV(
        totalSales: Double,
        totalExpenses: Double
    ): String {

        val profit = totalSales - totalExpenses

        return """
            RSHOTS COMPANY LIMITED
            FINANCIAL REPORT
            
            --------------------------
            TOTAL SALES: KES $totalSales
            TOTAL EXPENSES: KES $totalExpenses
            NET PROFIT: KES $profit
            --------------------------
            
            Generated by RShots Billing System
        """.trimIndent()
    }
}